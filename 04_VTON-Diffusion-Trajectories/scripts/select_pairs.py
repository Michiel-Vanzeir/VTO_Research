"""
Write cluster/pairs.txt: the garment pairs for the trajectory comparison
(read by cluster/submit.sh and compare_trajectories.py).

Garments are grouped in CATEGORIES of one visual property each, with several
garments per category, so results can be averaged per category instead of
resting on a single garment. Each garment is paired with the person it is
assigned to in the dataset's standard unpaired test split (test_pairs.txt),
the usual VITON-HD evaluation setting.

The garment lists are HAND-CURATED from the VITON-HD test set. IDM-VTON's
garment tags (vitonhd_test_tagged.json) were tried first, but they are too
noisy for this: "Dot" included plain white tops and a knit polo, "Check" a
plain pink top and a zigzag print, "Solid" picked 5 black tops out of 6. So
candidates were pre-filtered with those tags, then chosen by eye:
  solid       plain fabric, deliberately spread over colors (color axis)
  lettering   large, legible text / logo
  graphic     one placed illustration (not an all-over print)
  stripe      clear stripes of different widths/colors, incl. vertical
  floral      all-over floral prints, large to small repeat
  dot         clear polka dots, large and small
  check       plaid / gingham
  structural  solid fabric with buttons, pockets, zip or peplum
All are ordinary opaque tops (no lace, mesh, sequins or see-through, which
confound the color/texture measurements). The 5 original pairs are the
first item of their category and keep their old names, so existing results
stay valid.

Usage:
    python scripts/select_pairs.py
"""
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
TEST_PAIRS = REPO_ROOT / "data" / "zalando-hd-resized" / "test_pairs.txt"
OUT = REPO_ROOT / "cluster" / "pairs.txt"

# The original 5 pairs: garment -> run name.
ORIGINAL_NAMES = {"00006_00": "pair1_solid", "00126_00": "pair2_logo", "00286_00": "pair3_stripe",
                  "00205_00": "pair4_print", "00034_00": "pair5_structural"}

CURATED = {
    "solid": ["00006_00", "14675_00", "10087_00", "07247_00", "04395_00", "12106_00"],
    "lettering": ["00126_00", "03838_00", "14673_00", "02268_00", "13987_00", "11638_00"],
    "graphic": ["05537_00", "04450_00", "07241_00", "00396_00", "07180_00", "13975_00"],
    "stripe": ["00286_00", "01474_00", "09520_00", "03267_00", "04818_00", "03003_00"],
    "floral": ["00205_00", "01689_00", "08871_00", "05056_00", "10885_00", "03126_00"],
    "dot": ["00095_00", "04137_00", "06802_00", "06196_00", "04972_00", "11102_00"],
    "check": ["07796_00", "07050_00", "03413_00", "06379_00", "05935_00", "13730_00"],
    "structural": ["00034_00", "01641_00", "12186_00", "03407_00", "01403_00", "00463_00"],
}


def main():
    cloth_to_person = {}
    for line in TEST_PAIRS.read_text().split("\n"):
        if line.strip():
            person, cloth = line.split()
            cloth_to_person[cloth[:-4]] = person[:-4]

    rows, persons = [], set()
    for cat, cloths in CURATED.items():
        n = 0
        for cloth in cloths:
            person = cloth_to_person[cloth]
            assert person not in persons, f"person {person} used twice"
            persons.add(person)
            if cloth in ORIGINAL_NAMES:
                name = ORIGINAL_NAMES[cloth]
            else:
                n += 1
                name = f"{cat}_{n:02d}"
            rows.append((name, cat, person, cloth))

    with open(OUT, "w") as f:
        f.write("# Generated by scripts/select_pairs.py -- edit the lists there, not this file.\n")
        f.write("# VITON-HD test split; person/garment pairing from test_pairs.txt (unpaired setting).\n")
        f.write("# Every model is run on every pair; run dirs are outputs/<model>_<name>.\n")
        f.write(f"# {'<name>':18}{'<category>':12}{'<person>':10}<cloth>\n")
        for name, cat, person, cloth in rows:
            f.write(f"{name:20}{cat:12}{person:10}{cloth}\n")
    print(f"[select] wrote {OUT}: {len(rows)} pairs, " + ", ".join(f"{c} {len(v)}" for c, v in CURATED.items()))


if __name__ == "__main__":
    main()
